import { createRequire } from 'node:module';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(path.join(root,'src/frontend/package.json'));
const {chromium}=require('playwright-core');
const executablePath=process.env.BROWSER_PATH || ['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync);
const browser=await chromium.launch({executablePath,headless:true});
const page=await browser.newPage();
const base=process.env.PROTOTYPE_URL || 'http://127.0.0.1:5173';
const checks=[];const errors=[];page.on('pageerror',e=>errors.push(e.message));
const out=path.join(root,'artifacts/prototype');mkdirSync(out,{recursive:true});
try{
 await page.goto(base+'/integration',{waitUntil:'networkidle'});
 // The route is loaded on demand: wait until the lazy chunk has rendered.
 await page.waitForFunction(()=>!document.body.innerText.includes('正在载入本页模块'));
 await page.getByRole('button',{name:'检查后端 Demo',exact:true}).click();
 await page.getByRole('button',{name:'检查后端 Demo',exact:true}).waitFor({state:'visible'});
 await page.waitForFunction(()=>document.body.innerText.split('契约通过（仅 Demo）').length-1===7);
 checks.push('seven explicit HTTP Demo contracts pass including connector capabilities');
 await page.getByLabel('我确认仅含虚构演示内容，无秘密或个人信息').check();
 await page.getByRole('button',{name:'提交演示反馈到后端',exact:true}).click();
 await page.waitForFunction(()=>document.body.innerText.includes('HTTP：201'));
 checks.push('feedback creates real in-memory record with HTTP201');
 const receipt=page.getByRole('complementary',{name:'反馈内存回执'});await receipt.waitFor();const id=await receipt.locator('code').textContent();
 const lookups=[];const listener=request=>{if(request.url().includes('/api/v1/feedback'))lookups.push({method:request.method(),url:request.url()});};page.on('request',listener);
 await receipt.getByRole('button',{name:'核对内存记录',exact:true}).click();await receipt.getByText('核对一致：读取时记录仍在内存中，不保证后续保留。',{exact:true}).waitFor();page.off('request',listener);
 assert.equal(lookups.length,1);assert.equal(lookups[0].method,'GET');assert.ok(lookups[0].url.endsWith('/feedback/'+id));
 checks.push('actual receipt lookup matches original submission with one GET and no duplicate POST');
 await page.route('**/api/v1/**',route=>route.fulfill({status:503,contentType:'application/problem+json',body:JSON.stringify({title:'Injected unavailable',isDemo:false})}));
 await page.getByRole('button',{name:'检查后端 Demo',exact:true}).click();
 await page.waitForFunction(()=>document.body.innerText.split('检查失败').length-1>=6);
 assert.ok((await page.locator('body').innerText()).includes('HTTP 503'));checks.push('injected503 remains failure no mock fallback');
 await page.unroute('**/api/v1/**');
 await page.route('**/api/v1/**',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({data:[],isDemo:false,persistence:'none'})}));
 await page.getByRole('button',{name:'检查后端 Demo',exact:true}).click();
 await page.waitForFunction(()=>document.body.innerText.includes('Demo 信封不符合契约'));
 checks.push('wrong envelope rejected despite HTTP200');
 await page.unroute('**/api/v1/**');
 await page.route('**/api/v1/connector-capabilities',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({data:Array.from({length:10},(_,i)=>({id:`false-claim-${i}`,name:'fixture',status:'planned',protocols:['HTTPS'],targetFamilies:['fixture'],candidateVendors:['fixture'],plannedReadCapabilities:['inventory'],implemented:true,liveVerified:true,writeEnabled:true})),isDemo:true,persistence:'none'})}));
 await page.getByRole('button',{name:'检查后端 Demo',exact:true}).click();
 await page.waitForFunction(()=>document.body.innerText.includes('连接器候选能力契约不符'));
 checks.push('unverified connector capability claims rejected');
 await page.unroute('**/api/v1/connector-capabilities');
 await page.route('**/api/v1/**',route=>route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({title:'SYNTHETIC_PRIVATE_DIAGNOSTIC_DO_NOT_RENDER'})}));
 await page.getByRole('button',{name:'检查后端 Demo',exact:true}).click();
 await page.waitForFunction(()=>document.body.innerText.includes('HTTP 500'));
 assert.ok(!(await page.content()).includes('SYNTHETIC_PRIVATE_DIAGNOSTIC_DO_NOT_RENDER'));checks.push('error body never enters rendered DOM');
 await page.unroute('**/api/v1/**');
 await page.route('**/api/v1/**',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({data:'x'.repeat(262145),isDemo:true,persistence:'none'})}));
 await page.getByRole('button',{name:'检查后端 Demo',exact:true}).click();
 await page.waitForFunction(()=>document.body.innerText.includes('响应超过256KiB上限'));
 checks.push('oversized response rejected before JSON display');
 assert.equal(errors.length,0);checks.push('no page errors');
 writeFileSync(path.join(out,'integration-results.json'),JSON.stringify({passed:true,checks},null,2));console.log(JSON.stringify({passed:true,checks},null,2));
} catch(error){writeFileSync(path.join(out,'integration-results.json'),JSON.stringify({passed:false,error:error.message,checks,errors},null,2));throw error;}finally{await browser.close();}
