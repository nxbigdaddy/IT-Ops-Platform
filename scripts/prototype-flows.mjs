import { createRequire } from 'node:module';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(root, 'src/frontend/package.json'));
const { chromium } = require('playwright-core');
const executablePath = process.env.BROWSER_PATH || ['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync);
const base = process.env.PROTOTYPE_URL || 'http://127.0.0.1:5173';
const browser = await chromium.launch({ executablePath, headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN' });
const errors = [], externalRequests = [], passed = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (/^https?:/.test(request.url()) && new URL(request.url()).origin !== new URL(base).origin) externalRequests.push(request.url()); });
const out = path.join(root,'artifacts/prototype'); mkdirSync(out,{recursive:true});
const check = (condition, name) => { assert.ok(condition,name); passed.push(name); };
try {
  await page.goto(base + '/assets');
  await page.getByLabel('搜索资产',{exact:true}).fill('FS-01');
  check(await page.locator('tbody tr').count() === 1, 'asset search filters one row');
  // Empty states must be explicit, not a silent blank table (tickets has no filter control yet).
  await page.goto(base + '/assets');
  await page.getByLabel('搜索资产',{exact:true}).fill('no-such-demo-item');
  check(await page.getByText('暂无符合条件的数据',{exact:true}).count() > 0, '/assets shows an explicit empty state');
  await page.getByLabel('搜索资产',{exact:true}).fill('');
  await page.goto(base + '/alerts');
  await page.getByLabel('告警级别',{exact:true}).selectOption('P1');
  await page.getByLabel('告警状态',{exact:true}).selectOption('已确认');
  check(await page.getByText('暂无符合条件的数据',{exact:true}).count() > 0, '/alerts shows an explicit empty state');
  await page.getByLabel('告警状态',{exact:true}).selectOption('全部状态');
  await page.getByLabel('告警级别',{exact:true}).selectOption('全部级别');
  await page.goto(base + '/tickets');
  await page.getByLabel('搜索工单',{exact:true}).fill('no-such-demo-item');
  check(await page.getByText('暂无符合条件的数据',{exact:true}).count() > 0, '/tickets shows an explicit empty state');
  check((await page.getByText(/显示 0 \/ \d+ 条模拟工单/).count()) > 0, '/tickets reports the filtered count');
  await page.getByLabel('搜索工单',{exact:true}).fill('');
  await page.getByLabel('工单状态',{exact:true}).selectOption('处理中');
  check(await page.locator('tbody tr').count() >= 1, '/tickets state filter keeps matching rows');
  await page.getByLabel('工单状态',{exact:true}).selectOption('全部状态');
  await page.goto(base + '/assets');
  await page.getByLabel('搜索资产',{exact:true}).fill('FS-01');
  await page.getByRole('button',{name:'详情',exact:false}).click();
  check(await page.locator('dialog').isVisible(),'asset details open');
  await page.keyboard.press('Escape');
  check(await page.locator('dialog').count() === 0,'Escape closes details');
  await page.goto(base + '/alerts');
  await page.getByRole('button',{name:'确认告警',exact:true}).first().click();
  await page.getByRole('button',{name:'创建工单',exact:true}).first().click();
  await page.goto(base + '/tickets');
  check(await page.getByText('文件服务器磁盘空间低于阈值',{exact:true}).count() === 1,'alert creates ticket');
  await page.reload();
  check(await page.getByText('文件服务器磁盘空间低于阈值',{exact:true}).count() === 1,'mock state survives reload');
  await page.goto(base + '/prompts');
  await page.getByLabel('提示词内容').fill('自动化回归用模拟提示词：仅输出已知事实和待确认项。');
  await page.getByRole('button',{name:'保存新版本',exact:true}).click();
  check(await page.getByText('当前已保存 v2',{exact:true}).count() === 1,'prompt version created');
  await page.getByRole('button',{name:'测试（模拟）',exact:true}).click();
  check((await page.locator('pre').innerText()).includes('不由模型生成'),'prompt output explicitly simulated');
  await page.getByRole('button',{name:'恢复此版本为新版本',exact:true}).last().click();
  check(await page.getByText('当前已保存 v3',{exact:true}).count() === 1,'prompt restore creates version');
  await page.goto(base + '/ai');
  await page.getByLabel('模拟端点 URL').fill('https://real-provider.example.com/v1');
  await page.getByRole('button',{name:'保存模拟配置',exact:true}).click();
  check((await page.locator('.toast[role=status]').innerText()).includes('仅允许'),'real endpoint is rejected');
  await page.goto(base + '/feedback');
  await page.getByLabel('反馈内容').fill('自动化模拟反馈：希望增加位置筛选。');
  await page.getByRole('button',{name:'添加反馈',exact:true}).click();
  check(await page.getByText('自动化模拟反馈：希望增加位置筛选。',{exact:true}).count() === 1,'feedback saved');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button',{name:'导出 JSON',exact:true}).click();
  const download = await downloadPromise; await download.saveAs(path.join(out,'test-feedback.json'));
  check(download.suggestedFilename().endsWith('.json'),'feedback export downloads JSON');
  await page.getByRole('button',{name:'重置演示数据',exact:true}).click();
  await page.getByRole('button',{name:'取消',exact:true}).click();
  check(await page.getByText('自动化模拟反馈：希望增加位置筛选。',{exact:true}).count() === 1,'reset cancel preserves feedback');
  await page.getByRole('button',{name:'重置演示数据',exact:true}).click();
  await page.getByRole('button',{name:'确认重置',exact:true}).click();
  check(await page.getByText('还没有符合条件的反馈',{exact:true}).count() === 1,'confirmed reset clears feedback');
  check(errors.length === 0,'no browser page errors');
  check(externalRequests.length === 0,'no external network requests');
  writeFileSync(path.join(out,'flow-results.json'),JSON.stringify({passed:true,checks:passed,errors,externalRequests},null,2));
  console.log(JSON.stringify({passed:true,checks:passed},null,2));
} catch(error) {
  await page.screenshot({path:path.join(out,'flow-failure.png'),fullPage:true});
  writeFileSync(path.join(out,'flow-results.json'),JSON.stringify({passed:false,checks:passed,error:error.message,errors,externalRequests},null,2)); throw error;
} finally {await browser.close();}
